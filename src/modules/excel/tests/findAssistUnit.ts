import assert from 'node:assert/strict';
import {createFindMatcher,findSpans,replaceLiteral,orderedAddresses,replacementText,type FindOptions} from '../core/editing/findModel';
import {assistContext,assistReferences,referenceSlot} from '../core/formula/formulaAssist';
const options:FindOptions={query:'a.b',caseSensitive:false,whole:false,source:'display'};
assert.equal(findSpans('A.B aXb a.b',options).length,2);
for(const text of ['A.B aXb a.b','a.b\n','','a.b','😀a.b'])for(const whole of [false,true])assert.equal(createFindMatcher({...options,whole})(text),findSpans(text,{...options,whole}).length>0);
assert.equal(replaceLiteral('A.B a.b',options,'$&'),'$& $&');
assert.deepEqual(findSpans('😀α😀', {...options,query:'😀'}),[{start:0,end:2},{start:3,end:5}]);
assert.equal(findSpans('aaA',{...options,query:'aa',whole:true}).length,0);
assert.equal(findSpans('alpha',{...options,query:'ALPHA',caseSensitive:true}).length,0);
assert.throws(()=>replacementText({address:'B2',text:'12.00',value:{kind:'number',value:12}},options,'3'),/数字格式/);
assert.throws(()=>replacementText({address:'B2',text:'12',value:{kind:'formula',value:'SUM(A1:A3)'}},options,'3'),/计算结果/);
assert.deepEqual(orderedAddresses(['!ref','B12','A2','B1','A2','A3'],{s:{r:1,c:0},e:{r:2,c:0}}),['A2','A3']);
assert.deepEqual(assistContext('=ro',3).suggestions.map(f=>f.name),['ROUND','ROUNDUP','ROUNDDOWN']);
assert.equal(assistContext('=IF(A1>0,ROUND(A1,',19).call?.name,'ROUND');
assert.equal(assistContext('=IF(A1>0,ROUND(A1,',19).call?.argument,1);
assert.equal(assistContext('="RO',4).suggestions.length,0);
const quotedName="=ROUND('a,b (SUM)'!A1,";
assert.equal(assistContext(quotedName,quotedName.length).call?.name,'ROUND');
assert.equal(assistContext(quotedName,quotedName.length).call?.argument,1);
assert.equal(referenceSlot('="A1',4,4),undefined);
assert.deepEqual(referenceSlot('=SUM(',5,5),{start:5,end:5});
assert.deepEqual(referenceSlot('=SUM(A1:B2)',6,8),{start:5,end:10});
assert.equal(referenceSlot('=SUM(A1:B2)',11,11),undefined);
assert.deepEqual(assistReferences('=IF(A1="B9",\'O\'\'Brien !\'!$B$2:C3,D4)').map(r=>[r.sheet,r.range]),[[undefined,'A1'],["O'Brien !",'B2:C3'],[undefined,'D4']]);
console.log('PASS Excel literal/Unicode find, replacement safety, autocomplete context and incomplete formula reference slots');
